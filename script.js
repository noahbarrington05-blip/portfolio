function endDesktopItemInteraction(event) {
  if (!desktopDragState || desktopDragState.pointerId !== event.pointerId) {
    return;
  }

  const draggedButton = desktopDragState.button;
  window.clearTimeout(desktopDragState.holdTimer);

  if (desktopDragState.dragging) {
    draggedButton.classList.remove("is-dragging");

    if (event.type === "pointercancel") {
      draggedButton.dataset.suppressClick = "false";
    } else {
      window.setTimeout(() => {
        draggedButton.dataset.suppressClick = "false";
      }, 0);
    }
  } else {
    draggedButton.dataset.suppressClick = "false";
  }

  if (draggedButton.hasPointerCapture(event.pointerId)) {
    draggedButton.releasePointerCapture(event.pointerId);
  }

  desktopDragState = null;
}

