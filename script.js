function startBootLoader() {
  if (!bootLoader) {
    return;
  }

  desktopShell.classList.add("is-booting");
  document.body.classList.add("is-booting");

  const minimumBootDelay = new Promise((resolve) => {
    window.setTimeout(resolve, BOOT_LOADER_DURATION);
  });

  const pageReady = document.readyState === "complete"
    ? Promise.resolve()
    : new Promise((resolve) => {
      window.addEventListener("load", resolve, { once: true });
    });

  Promise.all([minimumBootDelay, pageReady]).then(() => {
    bootLoader.classList.add("is-hidden");
    desktopShell.classList.remove("is-booting");
    document.body.classList.remove("is-booting");
  });
}

