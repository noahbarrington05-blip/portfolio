function clampDesktopItemPosition(x, y, item) {
  const gridRect = desktopGrid.getBoundingClientRect();
  const maxX = Math.max(0, gridRect.width - item.offsetWidth);
  const maxY = Math.max(0, gridRect.height - item.offsetHeight);

  return {
    x: clamp(x, 0, maxX),
    y: clamp(y, 0, maxY)
  };
}

function clampFinderLikeItemPosition(gridElement, x, y, item) {
  const gridRect = gridElement.getBoundingClientRect();
  const maxX = Math.max(FINDER_EDGE_OFFSET, gridRect.width - item.offsetWidth - FINDER_EDGE_OFFSET);
  const maxY = Math.max(FINDER_EDGE_OFFSET, gridRect.height - item.offsetHeight - FINDER_EDGE_OFFSET);

  return {
    x: clamp(x, FINDER_EDGE_OFFSET, maxX),
    y: clamp(y, FINDER_EDGE_OFFSET, maxY)
  };
}

function clampFinderItemPosition(x, y, item) {
  return clampFinderLikeItemPosition(finderItemGrid, x, y, item);
}

function clampBinItemPosition(x, y, item) {
  return clampFinderLikeItemPosition(binItemGrid, x, y, item);
}

function getDefaultDesktopItemPosition(index, item) {
  const gridRect = desktopGrid.getBoundingClientRect();
  const preset = DESKTOP_LAYOUT_PRESETS[index];

  if (preset) {
    const availableWidth = Math.max(0, gridRect.width - item.offsetWidth - DESKTOP_EDGE_OFFSET * 2);
    const availableHeight = Math.max(0, gridRect.height - item.offsetHeight - DESKTOP_EDGE_OFFSET * 2);

    return clampDesktopItemPosition(
      DESKTOP_EDGE_OFFSET + availableWidth * preset.x,
      DESKTOP_EDGE_OFFSET + availableHeight * preset.y,
      item
    );
  }

  const totalWidth = item.offsetWidth * DESKTOP_COLUMNS + DESKTOP_COLUMN_GAP * (DESKTOP_COLUMNS - 1);
  const startX = Math.max(DESKTOP_EDGE_OFFSET, gridRect.width - totalWidth - DESKTOP_EDGE_OFFSET);
  const column = index % DESKTOP_COLUMNS;
  const row = Math.floor(index / DESKTOP_COLUMNS);

  return clampDesktopItemPosition(
    startX + column * (item.offsetWidth + DESKTOP_COLUMN_GAP),
    DESKTOP_EDGE_OFFSET + row * (item.offsetHeight + DESKTOP_ROW_GAP),
    item
  );
}

function getDefaultFinderLikeItemPosition(gridElement, index, item) {
  const gridRect = gridElement.getBoundingClientRect();
  const availableWidth = Math.max(0, gridRect.width - FINDER_EDGE_OFFSET * 2);
  const columns = Math.max(1, Math.floor((availableWidth + FINDER_COLUMN_GAP) / (item.offsetWidth + FINDER_COLUMN_GAP)));
  const column = index % columns;
  const row = Math.floor(index / columns);

  return clampFinderLikeItemPosition(
    gridElement,
    FINDER_EDGE_OFFSET + column * (item.offsetWidth + FINDER_COLUMN_GAP),
    FINDER_EDGE_OFFSET + row * (item.offsetHeight + FINDER_ROW_GAP),
    item
  );
}

function getDefaultFinderItemPosition(index, item) {
  return getDefaultFinderLikeItemPosition(finderItemGrid, index, item);
}

function getDefaultBinItemPosition(index, item) {
  return getDefaultFinderLikeItemPosition(binItemGrid, index, item);
}

function layoutDesktopItems() {
  projects.forEach((project, index) => {
    const item = desktopItems.get(project.id);

    if (!item) {
      return;
    }

    const savedPosition = desktopPositions.get(project.id);
    const nextPosition = savedPosition?.customPosition
      ? clampDesktopItemPosition(savedPosition.x, savedPosition.y, item)
      : getDefaultDesktopItemPosition(index, item);

    desktopPositions.set(project.id, {
      ...nextPosition,
      customPosition: Boolean(savedPosition?.customPosition)
    });

    setDesktopItemPosition(item, nextPosition);
  });
}

