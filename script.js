function animateWindow(trigger) {
  const triggerBox = trigger.querySelector(".desktop-item__preview, .finder-item__preview") || trigger;
  const startRect = triggerBox.getBoundingClientRect();
  const endRect = infoWindow.getBoundingClientRect();
  const startCenterX = startRect.left + startRect.width / 2;
  const startCenterY = startRect.top + startRect.height / 2;
  const endCenterX = endRect.left + endRect.width / 2;
  const endCenterY = endRect.top + endRect.height / 2;
  const deltaX = startCenterX - endCenterX;
  const deltaY = startCenterY - endCenterY;
  const scaleX = clamp(startRect.width / endRect.width, 0.12, 0.95);
  const scaleY = clamp(startRect.height / endRect.height, 0.12, 0.95);
  const currentX = getWindowOffsetCssValue(infoWindow, "--window-offset-x");
  const currentY = getWindowOffsetCssValue(infoWindow, "--window-offset-y");

  stopWindowAnimation();

  windowAnimation = infoWindow.animate(
    [
      {
        transform: `translate(calc(-50% + ${currentX} + ${deltaX}px), calc(-50% + ${currentY} + ${deltaY}px)) scale(${scaleX}, ${scaleY})`,
        opacity: 0.18,
        filter: "blur(0.7rem)"
      },
      {
        transform: `translate(calc(-50% + ${currentX}), calc(-50% + ${currentY})) scale(1)`,
        opacity: 1,
        filter: "blur(0rem)"
      }
    ],
    {
      duration: 430,
      easing: "cubic-bezier(0.16, 1, 0.3, 1)",
      fill: "both"
    }
  );

  windowAnimation.onfinish = () => {
    windowAnimation?.cancel();
    windowAnimation = null;
  };
}

function animateWindowClose() {
  if (infoWindow.classList.contains("info-window--hidden")) {
    return;
  }

  const activeProject = activeProjectCollection[activeProjectIndex];
  const target = activeTrigger || getProjectTrigger(activeProject?.id);
  const targetBox = target?.querySelector(".desktop-item__preview, .finder-item__preview") || target;

  if (!targetBox) {
    updateWindowVisibility(false);
    setDockActive(-1);
    setActiveProjectItem("");
    return;
  }

  const endRect = targetBox.getBoundingClientRect();
  const startRect = infoWindow.getBoundingClientRect();
  const startCenterX = startRect.left + startRect.width / 2;
  const startCenterY = startRect.top + startRect.height / 2;
  const endCenterX = endRect.left + endRect.width / 2;
  const endCenterY = endRect.top + endRect.height / 2;
  const deltaX = endCenterX - startCenterX;
  const deltaY = endCenterY - startCenterY;
  const scaleX = clamp(endRect.width / startRect.width, 0.12, 0.95);
  const scaleY = clamp(endRect.height / startRect.height, 0.12, 0.95);
  const currentX = getWindowOffsetCssValue(infoWindow, "--window-offset-x");
  const currentY = getWindowOffsetCssValue(infoWindow, "--window-offset-y");

  stopWindowAnimation();

  windowAnimation = infoWindow.animate(
    [
      {
        transform: `translate(calc(-50% + ${currentX}), calc(-50% + ${currentY})) scale(1)`,
        opacity: 1,
        filter: "blur(0rem)"
      },
      {
        transform: `translate(calc(-50% + ${currentX} + ${deltaX}px), calc(-50% + ${currentY} + ${deltaY}px)) scale(${scaleX}, ${scaleY})`,
        opacity: 0,
        filter: "blur(0.6rem)"
      }
    ],
    {
      duration: 320,
      easing: "cubic-bezier(0.4, 0, 1, 1)",
      fill: "both"
    }
  );

  windowAnimation.onfinish = () => {
    updateWindowVisibility(false);
    setDockActive(-1);
    setActiveProjectItem("");
    windowAnimation?.cancel();
    windowAnimation = null;
  };
}

