function startDesktopItemInteraction(event, index, button) {
  if (event.button !== 0 || desktopDragState) {
    return;
  }

  const projectId = projects[index].id;
  const currentPosition = desktopPositions.get(projectId);

  if (!currentPosition) {
    return;
  }

  const itemRect = button.getBoundingClientRect();
  button.setPointerCapture(event.pointerId);

  desktopDragState = {
    pointerId: event.pointerId,
    projectId,
    button,
    dragging: false,
    pointerOffsetX: event.clientX - itemRect.left,
    pointerOffsetY: event.clientY - itemRect.top,
    holdTimer: window.setTimeout(() => {
      if (!desktopDragState || desktopDragState.pointerId !== event.pointerId) {
        return;
      }

      desktopDragState.dragging = true;
      button.dataset.suppressClick = "true";
      button.classList.add("is-dragging");
    }, DESKTOP_HOLD_DELAY)
  };
}

