function shouldUsePortraitDock(viewportWidth = window.innerWidth, viewportHeight = window.innerHeight) {
  const isPortraitViewport = viewportHeight > viewportWidth;
  const isCompactLandscape = viewportWidth <= 1180 && viewportHeight <= 820;

  return isPortraitViewport || isCompactLandscape;
}

function hasPortraitDockLayout() {
  return (
    desktopShell.classList.contains("is-portrait-dock") ||
    document.body.classList.contains("is-portrait-dock")
  );
}

function applyDockLayoutMode() {
  const usePortraitDock = shouldUsePortraitDock();
  desktopShell.classList.toggle("is-portrait-dock", usePortraitDock);
  document.body.classList.toggle("is-portrait-dock", usePortraitDock);
}

function updateDockMagnification(event) {
  const isPortraitDock = hasPortraitDockLayout();

  dockItems.forEach((item) => {
    const icon = item.querySelector(".dock-item__icon");

    if (!icon) {
      return;
    }

    const rect = icon.getBoundingClientRect();
    const center = isPortraitDock ? rect.top + rect.height / 2 : rect.left + rect.width / 2;
    const pointer = isPortraitDock ? event.clientY : event.clientX;
    const distance = Math.abs(pointer - center);
    const influence = Math.max(0, 1 - distance / 140);
    const scale = 1 + influence * 0.26;
    const shiftX = isPortraitDock ? `${influence * 0.62}rem` : "0px";
    const shiftY = isPortraitDock ? "0px" : `${-influence * 0.62}rem`;

    icon.style.setProperty("--dock-scale", scale.toFixed(3));
    icon.style.setProperty("--dock-shift-x", shiftX);
    icon.style.setProperty("--dock-shift-y", shiftY);
  });
}

function startWindowDrag(windowElement, captureElement, event) {
  if (event.button !== 0 || event.target.closest(".traffic-lights")) {
    return;
  }

  if (!windowElement) {
    return;
  }

  if (windowElement === infoWindow) {
    stopWindowAnimation();
  }

  const rect = windowElement.getBoundingClientRect();
  windowInteractionState = {
    type: "drag",
    pointerId: event.pointerId,
    element: windowElement,
    captureElement,
    startX: event.clientX,
    startY: event.clientY,
    originX: getWindowMetricValue(windowElement, "--window-offset-x"),
    originY: getWindowMetricValue(windowElement, "--window-offset-y"),
    width: rect.width,
    height: rect.height
  };

  captureElement.setPointerCapture(event.pointerId);
  event.preventDefault();
}

function startWindowResize(windowElement, captureElement, event) {
  if (event.button !== 0) {
    return;
  }
  const config = windowElement ? getManagedWindowConfig(windowElement) : null;

  if (!windowElement || !config) {
    return;
  }

  if (windowElement === infoWindow) {
    stopWindowAnimation();
  }

  const rect = windowElement.getBoundingClientRect();
  windowInteractionState = {
    type: "resize",
    pointerId: event.pointerId,
    element: windowElement,
    captureElement,
    config,
    startX: event.clientX,
    startY: event.clientY,
    originWidth: rect.width,
    originHeight: rect.height,
    originX: getWindowMetricValue(windowElement, "--window-offset-x"),
    originY: getWindowMetricValue(windowElement, "--window-offset-y")
  };

  captureElement.setPointerCapture(event.pointerId);
  event.preventDefault();
}

function onManagedWindowPointerDown(event) {
  const windowElement = event.currentTarget;
  const resizeHandle = event.target.closest(".window-resize-handle");

  if (resizeHandle) {
    startWindowResize(windowElement, resizeHandle, event);
    return;
  }

  const chrome = event.target.closest(".info-window__chrome, .app-window__chrome");

  if (!chrome) {
    return;
  }

  startWindowDrag(windowElement, chrome, event);
}

function updateWindowInteraction(event) {
  if (!windowInteractionState || windowInteractionState.pointerId !== event.pointerId) {
    return;
  }

  if (windowInteractionState.type === "drag") {
    const nextOffsets = clampWindowOffsets(
      windowInteractionState.width,
      windowInteractionState.height,
      windowInteractionState.originX + event.clientX - windowInteractionState.startX,
      windowInteractionState.originY + event.clientY - windowInteractionState.startY
    );

    setWindowOffsets(windowInteractionState.element, nextOffsets.x, nextOffsets.y);
    return;
  }

  const nextSize = clampWindowSize(
    windowInteractionState.config,
    windowInteractionState.originWidth + event.clientX - windowInteractionState.startX,
    windowInteractionState.originHeight + event.clientY - windowInteractionState.startY
  );
  const nextOffsets = clampWindowOffsets(
    nextSize.width,
    nextSize.height,
    windowInteractionState.originX + (nextSize.width - windowInteractionState.originWidth) / 2,
    windowInteractionState.originY + (nextSize.height - windowInteractionState.originHeight) / 2
  );

  setWindowSize(windowInteractionState.element, nextSize.width, nextSize.height);
  setWindowOffsets(windowInteractionState.element, nextOffsets.x, nextOffsets.y);
  updateWindowCompactState(windowInteractionState.element, nextSize.width);
}

function endWindowInteraction(event) {
  if (!windowInteractionState || windowInteractionState.pointerId !== event.pointerId) {
    return;
  }

  const interactedElement = windowInteractionState.element;

  if (windowInteractionState.captureElement?.hasPointerCapture(event.pointerId)) {
    windowInteractionState.captureElement.releasePointerCapture(event.pointerId);
  }

  syncManagedWindowLayout(interactedElement);

  if (interactedElement === finderWindow) {
    layoutFinderItems();
  }

  if (interactedElement === binWindow) {
    layoutBinItems();
  }

  windowInteractionState = null;
}

function bindManagedWindowInteractions() {
  managedWindows.forEach(({ element }) => {
    element.addEventListener("pointerdown", onManagedWindowPointerDown);
  });
}

